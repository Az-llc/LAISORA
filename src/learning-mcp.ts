export function learningToolReply(result: LearningResult) {
  return { ...(!result.ok ? { isError: true } : {}), content: [{ type: "text" as const, text: JSON.stringify(result) }] };
}

export class LearningRootGate {
  private readonly marks = new Map<string, number>();

  constructor(private readonly now: () => number = Date.now, private readonly log: (message: string) => void = () => {}) {}

  readonly hook: Sdk.HookCallback = async (input) => {
    const value = input as unknown as Record<string, unknown>;
    if (!LEARNING_TOOL_NAMES.includes(String(value.tool_name))) return {};
    if (value.hook_event_name !== "PreToolUse") { this.revoke(value.tool_use_id); return {}; }
    return failClosedGuard(() => {
      if (value.agent_id !== undefined) {
        return { hookSpecificOutput: { hookEventName: "PreToolUse" as const, permissionDecision: "deny" as const,
          permissionDecisionReason: JSON.stringify(CALLER_UNVERIFIED) } };
      }
      if (typeof value.tool_use_id === "string" && value.tool_use_id) this.mark(value.tool_use_id);
      return {};
    }, this.log);
  };

  private mark(id: string): void {
    for (const [key, expiry] of this.marks) if (expiry <= this.now()) this.marks.delete(key);
    this.marks.delete(id);
    this.marks.set(id, this.now() + ROOT_MARK_TTL_MS);
    for (const key of this.marks.keys()) {
      if (this.marks.size <= ROOT_MARK_CAP) break;
      this.marks.delete(key);
    }
  }

  private live(id: string): boolean {
    const expiry = this.marks.get(id);
    if (expiry !== undefined && expiry > this.now()) return true;
    this.marks.delete(id);
    return false;
  }

  hold(id: unknown): void { if (typeof id === "string" && this.live(id)) this.marks.set(id, this.now() + ROOT_MARK_HOLD_MS); }
  release(id: unknown): void { if (typeof id === "string" && this.live(id)) this.marks.set(id, this.now() + ROOT_MARK_TTL_MS); }
  revoke(id: unknown): void { if (typeof id === "string") this.marks.delete(id); }
  clear(): void { this.marks.clear(); }

  consume(extra: unknown): boolean {
    const meta = extra && typeof extra === "object" ? (extra as { _meta?: unknown })._meta : undefined;
    const id = meta && typeof meta === "object" ? (meta as Record<string, unknown>)[TOOL_USE_META_KEY] : undefined;
    if (typeof id !== "string" || !this.live(id)) return false;
    this.marks.delete(id);
    return true;
  }
}

const requestId = z.string().describe(`Opaque request ID: 1-${RECORD_REF_MAX_LENGTH} characters from ${RECORD_REF_ALPHABET}; reuse only for identical input.`);
const target = {
  executor: z.enum(["claude", "codex", "agy"]),
  model: z.string().describe("Concrete model UI name from the Host's successful CLI list; no aliases."),
  effort: z.string().describe("An executor effort, or none for a model without effort."),
  role: z.string().describe("general or a configured roster role; no child or unknown roles."),
  text: z.string().describe("One line within 300 Unicode code points, without URLs: condition -> observed behavior -> limitation."),
};
export const LEARNING_INPUTS = {
  observe: z.looseObject({ requestId, ...target, runs: z.array(z.string()).min(1).max(8).describe("Cited Claude agentIds or external run references from this conversation.") }),
  propose: z.looseObject({ requestId, text: z.string().describe("One model-independent orchestration practice, one line within 500 code points. Never delivered.") }),
  correct: z.looseObject({ requestId, item: z.string().describe("The #item id shown on a delivered claim or rule line."),
    action: z.enum(["retract", "replace"]), reason: z.string().describe("Reason for correction, one private-free line within 300 code points."),
    text: target.text.optional().describe("Required for replace; forbidden for retract. The replacement observation."),
    runs: z.array(z.string()).min(1).max(8).optional().describe("Cited Claude agentIds or external run references; required for claims, target rules and replacement observations.") }),
};

export function createLearningMcpServer(sdk: Pick<typeof Sdk, "createSdkMcpServer" | "tool">, gate: LearningRootGate,
  record: (input: unknown, rootVerified: boolean, kind: LearningToolKind) => Promise<LearningResult>) {
  return sdk.createSdkMcpServer({ name: "laisora_learning", tools: (Object.keys(LEARNING_INPUTS) as LearningToolKind[]).map(kind => sdk.tool(kind,
    kind === "observe" ? "Record a model-specific observation: condition -> observed behavior -> limitation. Cite the runs it is about. Only the verified root may record."
      : kind === "correct" ? "Retract or replace a delivered item using its #item id and cited runs. Only the verified root may correct."
      : "Record a model-independent orchestration practice for the developer. Never delivered. Only the verified root may record.",
    LEARNING_INPUTS[kind] as unknown as Record<string, z.ZodType>,
    async (input, extra) => learningToolReply(await record(input, gate.consume(extra), kind)))) });
}
